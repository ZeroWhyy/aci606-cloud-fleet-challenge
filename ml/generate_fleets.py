"""Generate independent fleets with the original, unchanged simulator."""
from __future__ import annotations
import argparse
import csv
import json
import random
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from simulator.core import make_robot, step_robot

def main() -> None:
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--fleets", type=int, default=40)
    p.add_argument("--robots", type=int, default=6)
    p.add_argument("--steps", type=int, default=60)
    p.add_argument("--seed", type=int, default=606)
    p.add_argument("--output", default="data/training.csv")
    args = p.parse_args()
    if min(args.fleets, args.robots, args.steps) < 1:
        p.error("fleets, robots and steps must be positive")
    out = Path(args.output)
    out.parent.mkdir(parents=True, exist_ok=True)
    rows = []
    for fleet_index in range(args.fleets):
        rng = random.Random(args.seed + fleet_index * 1009)
        robots = [make_robot(i + 1, rng) for i in range(args.robots)]
        for step in range(args.steps):
            for robot in robots:
                sample, status = step_robot(robot, rng)
                # Make generated bytes independent of the wall clock.
                sample["timestamp"] = 1780000000.0 + fleet_index * 100000 + step
                rows.append({"fleet_id": f"F{fleet_index:03d}", **sample, "status": status})
    with out.open("w", newline="", encoding="utf-8") as f:
        writer = csv.DictWriter(f, fieldnames=list(rows[0]))
        writer.writeheader()
        writer.writerows(rows)
    out.with_suffix(".generation.json").write_text(
        json.dumps({k: v for k, v in vars(args).items() if k != "output"}, indent=2) + "\n", encoding="utf-8")
    print(f"Generated {len(rows)} rows from {args.fleets} independent fleets: {out}")

if __name__ == "__main__":
    main()
